#!/usr/bin/env python
"""Generate the code-grounded reference pages for the OEDISI docs.

This script produces four MyST pages directly from the live code so they can
never drift from the implementation:

* ``advanced/cli.md``          — from Click introspection of the ``oedisi`` CLI
* ``advanced/api.md``          — from griffe docstrings + Pydantic model fields
* ``advanced/data-types.md``   — from ``oedisi.types.data_types``
* ``beginner/component-catalog.md`` — from the frontend registry + each
  component's ``component_definition.json``

Run it from anywhere::

    python docs/tools/generate.py                 # regenerate all pages
    python docs/tools/generate.py --check         # fail if pages are stale
    python docs/tools/generate.py --targets cli api data-types

The component catalog needs the sibling ``oedisi-components`` and
``oedisi-frontend-app`` repositories; the other three pages need only the
installed ``oedisi`` package.
"""

from __future__ import annotations

import argparse
import inspect
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

DOCS = Path(__file__).resolve().parents[1]
REPO_ROOT = DOCS.parent
WORKSPACE = REPO_ROOT.parent

GENERATED_NOTE = (
    "% DO NOT EDIT — generated by docs/tools/generate.py from the live code.\n"
    "% Re-run `python docs/tools/generate.py` after changing the CLI, the\n"
    "% `oedisi` API, the data types, or the component registry.\n"
)


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def clean_type(annotation: Any) -> str:
    """Render a type annotation without module noise."""
    if annotation is inspect.Signature.empty or annotation is None:
        return ""
    s = annotation if isinstance(annotation, str) else _annotation_repr(annotation)
    s = s.replace("typing.", "")
    s = re.sub(r"<class '([^']+)'>", r"\1", s)
    s = re.sub(r"ForwardRef\('([^']+)'\)", r"\1", s)
    # Make object reprs reproducible: drop memory addresses and simplify callables.
    s = re.sub(r"\s+at\s+0x[0-9a-fA-F]+", "", s)
    s = re.sub(r"<(?:function|built-in function|method)\s+([\w.]+)[^>]*>", r"\1", s)
    # Strip dotted module prefixes: foo.bar.Baz -> Baz
    s = re.sub(r"(?:[A-Za-z_][\w]*\.)+([A-Za-z_]\w*)", r"\1", s)
    s = s.replace("NoneType", "None")
    return s.strip()


def _annotation_repr(annotation: Any) -> str:
    try:
        return str(annotation)
    except Exception:  # pragma: no cover - defensive
        return repr(annotation)


def md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _griffe_package():
    import griffe

    if not hasattr(_griffe_package, "_cache"):
        _griffe_package._cache = griffe.load(
            "oedisi", submodules=True, allow_inspection=True
        )
    return _griffe_package._cache


def griffe_doc(qualname: str, live_obj: Any = None) -> str:
    """Return a docstring via griffe, falling back to ``inspect``."""
    try:
        obj = _griffe_package()
        for part in qualname.split("."):
            obj = obj[part]
        if obj.docstring and obj.docstring.value:
            return inspect.cleandoc(obj.docstring.value)
    except Exception:
        pass
    if live_obj is not None:
        return inspect.getdoc(live_obj) or ""
    return ""


# --------------------------------------------------------------------------- #
# Pydantic rendering
# --------------------------------------------------------------------------- #
def is_pydantic_model(obj: Any) -> bool:
    try:
        from pydantic import BaseModel

        return isinstance(obj, type) and issubclass(obj, BaseModel)
    except Exception:
        return False


def field_rows(model: type, only_own: bool = False) -> list[tuple[str, str, str, str]]:
    """Return (name, type, required/default, description) rows for a model."""
    from pydantic import BaseModel

    parent_fields: set[str] = set()
    if only_own:
        for base in model.__bases__:
            if is_pydantic_model(base) and base is not BaseModel:
                parent_fields |= set(getattr(base, "model_fields", {}))

    rows: list[tuple[str, str, str, str]] = []
    for fname, field in model.model_fields.items():
        if only_own and fname in parent_fields:
            continue
        typ = clean_type(field.annotation)
        if field.is_required():
            req = "**required**"
        else:
            default = field.default
            req = f"`{default!r}`" if default is not None else "`None`"
        desc = md_escape(field.description or "")
        rows.append((fname, typ, req, desc))
    return rows


def render_field_table(rows: list[tuple[str, str, str, str]]) -> str:
    if not rows:
        return ""
    out = ["| Field | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for name, typ, req, desc in rows:
        out.append(f"| `{name}` | `{typ}` | {req} | {desc} |")
    return "\n".join(out) + "\n"


