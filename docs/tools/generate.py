def documented_data_types() -> list[tuple[str, type]]:
    """The data-type models to document — the exact set the catalog links to.

    Includes concrete models defined in the module *and* the ``RootModel`` list
    wrappers (e.g. ``CommandList``) that live in the module namespace but whose
    ``__module__`` is pydantic's.
    """
    import oedisi.types.data_types as dt
    from pydantic import BaseModel, RootModel

    pairs: list[tuple[str, type]] = []
    for name, obj in vars(dt).items():
        if not (isinstance(obj, type) and issubclass(obj, BaseModel)):
            continue
        if obj in (BaseModel, RootModel) or not name[:1].isupper():
            continue
        pairs.append((name, obj))
    return pairs


def render_data_types() -> str:
    from pydantic import RootModel

    pairs = documented_data_types()
    module_names = {name for name, _ in pairs}

    lines = [
        "---",
        "title: Data types",
        "description: The oedisi.types models components use to exchange data.",
        "---",
        "",
        GENERATED_NOTE,
        "# Data types",
        "",
        "Components exchange typed values defined as [Pydantic](https://docs.pydantic.dev)",
        "models in `oedisi.types.data_types`. A port's `type` in a",
        "`component_definition.json` refers to one of the models below. Many concrete",
        "types are thin subclasses that inherit their fields from a base array type.",
        "",
        "## Summary",
        "",
        "| Type | Inherits |",
        "| --- | --- |",
    ]
    for name, m in pairs:
        base = m.__bases__[0].__name__
        base_link = (
            f"[`{base}`](#datatype-{slug(base)})"
            if base in module_names
            else f"`{base}`"
        )
        lines.append(f"| [`{name}`](#datatype-{slug(name)}) | {base_link} |")
    lines.append("")

    for name, m in pairs:
        base = m.__bases__[0].__name__
        lines.append(f"(datatype-{slug(name)})=")
        lines.append(f"### {name}")
        lines.append("")
        if base in module_names:
            lines.append(f"Inherits [`{base}`](#datatype-{slug(base)}).")
        else:
            lines.append(f"Inherits `{base}`.")
        lines.append("")
        if issubclass(m, RootModel):
            root_ann = clean_type(m.model_fields["root"].annotation)
            lines.append(f"A list wrapper around `{root_ann}`.")
            lines.append("")
            continue
        if m.__module__ == "oedisi.types.data_types":
            own_doc = m.__dict__.get("__doc__")
            if own_doc:
                lines.append(inspect.cleandoc(own_doc).strip())
                lines.append("")
        table = render_field_table(field_rows(m, only_own=True))
        if table:
            lines.append("**Fields**")
            lines.append("")
            lines.append(table)
    return "\n".join(lines)


