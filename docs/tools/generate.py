def _resolve_registry(registry: Path, components: Path) -> dict[str, Path]:
    raw = json.loads(registry.read_text())
    resolved: dict[str, Path] = {}
    for display, path in raw.items():
        p = path.replace("${OEDISI_COMPONENTS}", str(components))
        resolved[display] = Path(p)
    return resolved


def _first_paragraph(readme: Path) -> str:
    para: list[str] = []
    for line in readme.read_text(errors="ignore").splitlines():
        s = line.strip()
        if not s:
            if para:
                break
            continue
        if s.startswith("#"):
            if para:
                break
            continue
        if s.startswith(("![", "[!", "<", "|", "```", "=", "-")):
            continue
        para.append(s)
    text = " ".join(para)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)  # unwrap links
    return md_escape(text)[:320]


def _component_description(def_path: Path) -> str:
    d = def_path.parent
    for _ in range(3):
        readme = d / "README.md"
        if readme.exists():
            desc = _first_paragraph(readme)
            if desc:
                return desc
        d = d.parent
    return ""


def render_catalog(registry: Path, components: Path) -> str:
    known_types = {name for name, _ in documented_data_types()}

    entries = _resolve_registry(registry, components)

    def type_cell(t: str) -> str:
        if not t:
            return "—"
        if t in known_types:
            return f"[`{t}`](../advanced/data-types.md#datatype-{slug(t)})"
        return f"`{t}`"

    lines = [
        "---",
        "title: Component catalog",
        "description: Reference of the components available in the OEDISI UI.",
        "---",
        "",
        GENERATED_NOTE,
        "# Component catalog",
        "",
        "These are the components registered with the web app. Each is a HELICS",
        "federate that consumes (`subscribes`) and produces (`publishes`) the typed",
        "[data types](../advanced/data-types.md) listed below. The **name** is what you",
        "see in the designer palette; the **folder** is where its code lives in",
        "`oedisi-components`.",
        "",
        "## All components",
        "",
        "| Component | Folder | Subscribes | Publishes |",
        "| --- | --- | --- | --- |",
    ]

    details: list[str] = []
    for display in sorted(entries):
        def_path = entries[display]
        if not def_path.exists():
            continue
        try:
            defn = json.loads(def_path.read_text())
        except Exception:
            continue
        directory = defn.get("directory") or def_path.parent.name
        din = defn.get("dynamic_inputs", []) or []
        dout = defn.get("dynamic_outputs", []) or []
        sin = defn.get("static_inputs", []) or []
        lines.append(
            f"| [{display}](#component-{slug(display)}) | `{directory}` | "
            f"{len(din)} | {len(dout)} |"
        )

        details.append(f"(component-{slug(display)})=")
        details.append(f"## {display}")
        details.append("")
        details.append(f"Folder: `{directory}`")
        details.append("")
        desc = _component_description(def_path)
        if desc:
            details.append(desc)
            details.append("")
        if sin:
            details.append("**Configuration** (`static_inputs`)")
            details.append("")
            details.append("| Port | Type |")
            details.append("| --- | --- |")
            for port in sin:
                details.append(
                    f"| `{port.get('port_id', '')}` | {type_cell(port.get('type', ''))} |"
                )
            details.append("")
        if din:
            details.append("**Subscribes** (`dynamic_inputs`)")
            details.append("")
            details.append("| Port | Type | Optional |")
            details.append("| --- | --- | --- |")
            for port in din:
                opt = "yes" if port.get("optional") else ""
                details.append(
                    f"| `{port.get('port_id', '')}` | {type_cell(port.get('type', ''))} | {opt} |"
                )
            details.append("")
        if dout:
            details.append("**Publishes** (`dynamic_outputs`)")
            details.append("")
            details.append("| Port | Type |")
            details.append("| --- | --- |")
            for port in dout:
                details.append(
                    f"| `{port.get('port_id', '')}` | {type_cell(port.get('type', ''))} |"
                )
            details.append("")

    lines.append("")
    lines.extend(details)
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Driver
# --------------------------------------------------------------------------- #
def build_pages(registry: Path, components: Path, targets: list[str]) -> dict[Path, str]:
    pages: dict[Path, str] = {}
    if "cli" in targets:
        pages[DOCS / "advanced" / "cli.md"] = render_cli()
    if "api" in targets:
        pages[DOCS / "advanced" / "api.md"] = render_api()
    if "data-types" in targets:
        pages[DOCS / "advanced" / "data-types.md"] = render_data_types()
    if "catalog" in targets:
        if registry.exists() and components.exists():
            pages[DOCS / "beginner" / "component-catalog.md"] = render_catalog(
                registry, components
            )
        else:
            print(
                f"[skip] catalog: registry ({registry}) or components ({components}) "
                "not found — skipping.",
                file=sys.stderr,
            )
    return pages


def main() -> int:
    default_registry = Path(
        os.environ.get(
            "OEDISI_FRONTEND_REGISTRY",
            WORKSPACE / "oedisi-frontend-app" / "server" / "components.json",
        )
    )
    default_components = Path(
        os.environ.get("OEDISI_COMPONENTS", WORKSPACE / "oedisi-components" / "Components")
    )

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=default_registry)
    parser.add_argument("--components", type=Path, default=default_components)
    parser.add_argument(
        "--targets",
        nargs="+",
        default=["cli", "api", "data-types", "catalog"],
        choices=["cli", "api", "data-types", "catalog"],
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if any generated page is out of date.",
    )
    args = parser.parse_args()

    pages = build_pages(args.registry, args.components, args.targets)

    stale: list[Path] = []
    for path, content in pages.items():
        content = content.rstrip() + "\n"
        if args.check:
            current = path.read_text() if path.exists() else ""
            if current != content:
                stale.append(path)
        else:
            path.write_text(content)
            print(f"[write] {path.relative_to(REPO_ROOT)}")

    if args.check and stale:
        print("Stale generated pages (run docs/tools/generate.py):", file=sys.stderr)
        for path in stale:
            print(f"  - {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
