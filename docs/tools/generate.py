# Page: CLI
# --------------------------------------------------------------------------- #
def _clean_cli_help(cmd) -> str:
    """User-facing help for a Click command, without the autodoc tail.

    Click hides everything after a form-feed in help output; some docstrings
    encode it literally as ``\f``. We also drop any trailing numpydoc
    ``Parameters`` section so the page is deterministic across Click versions.
    """
    text = cmd.help or ""
    for sep in ("\x0c", "\\f"):
        text = text.split(sep, 1)[0]
    text = re.split(r"\n[ \t]*Parameters[ \t]*\n[ \t]*-{3,}", text)[0]
    return inspect.cleandoc(text).strip()


def render_cli() -> str:
    import click

    from oedisi.tools import cli

    lines = [
        "---",
        "title: Command-line interface",
        "description: Every oedisi command and option, generated from the CLI.",
        "---",
        "",
        GENERATED_NOTE,
        "# Command-line interface",
        "",
        "The `oedisi` command-line tool builds and runs simulations. Installing the",
        "`oedisi` package puts it on your `PATH`; run `oedisi --help` to see the same",
        "summary reproduced here.",
        "",
        "```text",
        "Usage: oedisi [OPTIONS] COMMAND [ARGS]...",
        "```",
        "",
        "## Commands",
        "",
    ]

    # Summary table
    lines.append("| Command | Summary |")
    lines.append("| --- | --- |")
    for name, cmd in sorted(cli.commands.items()):
        summary = md_escape(_clean_cli_help(cmd).split("\n", 1)[0])
        lines.append(f"| [`oedisi {name}`](#cli-{slug(name)}) | {summary} |")
    lines.append("")

    for name, cmd in sorted(cli.commands.items()):
        lines.append(f"(cli-{slug(name)})=")
        lines.append(f"### `oedisi {name}`")
        lines.append("")
        help_body = _clean_cli_help(cmd)
        if help_body:
            lines.append(help_body)
            lines.append("")
        lines.append("```text")
        lines.append(f"Usage: oedisi {name} [OPTIONS]")
        lines.append("```")
        lines.append("")

        opts = [p for p in cmd.params if isinstance(p, click.Option)]
        opts = [p for p in opts if p.name != "help"]
        if opts:
            lines.append("| Option | Type | Default | Description |")
            lines.append("| --- | --- | --- | --- |")
            for p in opts:
                flags = "`" + "`, `".join(p.opts + p.secondary_opts) + "`"
                if p.is_flag:
                    typ = "flag"
                else:
                    typ = getattr(p.type, "name", "") or ""
                if p.required:
                    default = "**required**"
                elif p.default is not None and p.default != ():
                    default = f"`{p.default!r}`"
                else:
                    default = "—"
                desc = md_escape(p.help or "")
                lines.append(f"| {flags} | {typ} | {default} | {desc} |")
            lines.append("")

    lines.append(":::{seealso}")
    lines.append("Building blocks these commands operate on: the")
    lines.append("[Python API](api.md) and the [multi-container workflow](multicontainer.md).")
    lines.append(":::")
    lines.append("")
    return "\n".join(lines)


