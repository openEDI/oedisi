def render_api() -> str:
    import importlib

    lines = [
        "---",
        "title: Python API reference",
        "description: Public classes and functions of the oedisi package.",
        "---",
        "",
        GENERATED_NOTE,
        "# Python API reference",
        "",
        "The `oedisi` package exposes the component framework used to describe and",
        "compile co-simulations. The reference below is generated from the package's",
        "own docstrings and Pydantic models. For the data models exchanged between",
        "components see [Data types](data-types.md); for the CLI see the",
        "[command-line interface](cli.md).",
        "",
    ]

    for title, module_path, griffe_prefix, names in API_SECTIONS:
        module = importlib.import_module(module_path)
        lines.append(f"## {title}")
        lines.append("")
        lines.append(f"Module: `{module_path}`")
        lines.append("")
        for objname in names:
            obj = getattr(module, objname, None)
            if obj is None:
                print(f"[skip] {module_path}.{objname} not found", file=sys.stderr)
                continue
            anchor = slug(objname)
            lines.append(f"(api-{anchor})=")
            kind = "class" if isinstance(obj, type) else "function"
            lines.append(f"### `{objname}` ({kind})")
            lines.append("")
            if isinstance(obj, type):
                # Only the class's own docstring — never an inherited one.
                own = obj.__dict__.get("__doc__")
                doc = griffe_doc(f"{griffe_prefix}.{objname}") or (
                    inspect.cleandoc(own) if own else ""
                )
            else:
                doc = griffe_doc(f"{griffe_prefix}.{objname}", obj)
                try:
                    sig = clean_type(str(inspect.signature(obj)))
                    lines.append(f"```python\n{objname}{sig}\n```")
                    lines.append("")
                except (TypeError, ValueError):
                    pass
            if doc:
                lines.append(_docstring_to_md(doc))
                lines.append("")
            if is_pydantic_model(obj):
                rows = field_rows(obj, only_own=False)
                table = render_field_table(rows)
                if table:
                    lines.append("**Fields**")
                    lines.append("")
                    lines.append(table)
    return "\n".join(lines)


def _docstring_to_md(doc: str) -> str:
    """Render a NumPy-style docstring body safely for MyST.

    We keep it simple and faithful: emit the docstring inside a fenced block if
    it contains section underlines, otherwise as prose.
    """
    if re.search(r"\n-{3,}\n", "\n" + doc):
        return f"```text\n{doc.strip()}\n```"
    return doc.strip()


